#!/usr/bin/env node
'use strict';
//
// Build the lspf PWA into www/ (no dependencies):
//
//   node build.js [--src ../node-lspf] [--out www]
//
//  www/lspf-bundle.js   node-lspf (lib/, apps/) + browser shims (src/) + embedded libraries
//                       (plib, plib-node, mlib, help, rexx, doc) mounted read-only on /lspf
//  www/sw.js            service worker (offline cache, versioned by the content)
//  www/icons/*.png      icons generated here
//  www/index.html, app.css, manifest.webmanifest   copied from public/
//
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const crypto = require('crypto');

const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 && args[i + 1] ? args[i + 1] : d; };
const HERE = __dirname;
const SRC = path.resolve(HERE, opt('--src', '../node-lspf'));
const OUT = path.resolve(HERE, opt('--out', 'www'));

if (!fs.existsSync(path.join(SRC, 'lib', 'session.js'))) {
  console.error(`node-lspf not found in ${SRC} (use --src DIR)`);
  process.exit(1);
}
if (!OUT.startsWith(HERE + path.sep)) { console.error('The output directory must be inside ' + HERE); process.exit(1); }

const pkg = JSON.parse(fs.readFileSync(path.join(SRC, 'package.json'), 'utf8'));
const BUILD = { version: pkg.version, date: new Date().toISOString() };

function walk(dir, rel = '') {
  const out = [];
  for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const r = rel ? rel + '/' + e.name : e.name;
    if (e.isDirectory()) out.push(...walk(dir, r));
    else if (e.isFile()) out.push(r);
  }
  return out.sort();
}

// ---------------------------------------------------------------------------------------------------------------
// Modules
// ---------------------------------------------------------------------------------------------------------------
const modules = [];
const addModule = (id, file) => {
  const src = fs.readFileSync(file, 'utf8').replace(/^#!.*\n/, '');
  if (file.endsWith('.json')) modules.push(`${JSON.stringify(id)}: ${JSON.stringify(src)}`);
  else modules.push(`${JSON.stringify(id)}: function (module, exports, require, __filename, __dirname, process, Buffer) {\n${src}\n}`);
};
for (const f of walk(path.join(HERE, 'src'))) if (f.endsWith('.js') && f !== 'loader.js') addModule('/pwa/' + f, path.join(HERE, 'src', f));
for (const d of ['lib', 'apps']) for (const f of walk(path.join(SRC, d))) if (f.endsWith('.js')) addModule(`/lspf/${d}/${f}`, path.join(SRC, d, f));
addModule('/lspf/package.json', path.join(SRC, 'package.json'));

// ---------------------------------------------------------------------------------------------------------------
// Read-only libraries (latin1 strings: one character per byte, decoded by the VFS like Node reads them)
// ---------------------------------------------------------------------------------------------------------------
const assets = [];
let assetBytes = 0;
for (const d of ['plib', 'plib-node', 'mlib', 'help', 'rexx', 'doc', 'apps', 'lib']) {
  const dir = path.join(SRC, d);
  if (!fs.existsSync(dir)) continue;
  for (const f of walk(dir)) {
    const b = fs.readFileSync(path.join(dir, f));
    assetBytes += b.length;
    assets.push(`${JSON.stringify(`/lspf/${d}/${f}`)}:${JSON.stringify(b.toString('latin1'))}`);
  }
}
for (const f of ['package.json', 'README.md', 'LICENSE']) {
  const p = path.join(SRC, f);
  if (fs.existsSync(p)) assets.push(`${JSON.stringify('/lspf/' + f)}:${JSON.stringify(fs.readFileSync(p).toString('latin1'))}`);
}

const bundle = [
  `/* lspf PWA ${BUILD.version} - generated by build.js on ${BUILD.date} from ${path.basename(SRC)} - GPL v3 */`,
  `self.__LSPF_BUILD__ = ${JSON.stringify(BUILD)};`,
  `self.__LSPF_ASSETS__ = {\n${assets.join(',\n')}\n};`,
  `self.__LSPF_MODULES__ = {\n${modules.join(',\n')}\n};`,
  fs.readFileSync(path.join(HERE, 'src', 'loader.js'), 'utf8'),
].join('\n');

// ---------------------------------------------------------------------------------------------------------------
// Icons (PNG written with zlib)
// ---------------------------------------------------------------------------------------------------------------
const CRC = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; }
  return (buf) => { let c = 0xffffffff; for (const b of buf) c = t[(c ^ b) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
})();
function png(w, h, rgba) {
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(CRC(td));
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6;
  const raw = Buffer.alloc((w * 4 + 1) * h);
  for (let y = 0; y < h; y++) rgba.copy(raw, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4);
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
const hex = (c) => [parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16), 255];
function segDist(px, py, ax, ay, bx, by) {
  const dx = bx - ax, dy = by - ay;
  const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)));
  return Math.hypot(px - ax - t * dx, py - ay - t * dy);
}
// A small 3270 screen: blue action bar, green prompt chevron, text lines, cursor, PF key bar
function iconColor(x, y, maskable) {
  if (maskable) { x = 0.5 + (x - 0.5) / 0.78; y = 0.5 + (y - 0.5) / 0.78; }
  else {
    const r = 0.2, cx = Math.min(Math.max(x, r), 1 - r), cy = Math.min(Math.max(y, r), 1 - r);
    if (Math.hypot(x - cx, y - cy) > r) return null;
  }
  const inR = (x0, y0, x1, y1) => x >= x0 && x < x1 && y >= y0 && y < y1;
  if (inR(0.16, 0.17, 0.84, 0.25)) return hex('#5b8cff');
  if (segDist(x, y, 0.2, 0.36, 0.33, 0.47) < 0.03 || segDist(x, y, 0.33, 0.47, 0.2, 0.58) < 0.03) return hex('#3fcf5f');
  if (inR(0.40, 0.44, 0.80, 0.50)) return hex('#30c8c8');
  if (inR(0.20, 0.64, 0.62, 0.69)) return hex('#3fcf5f');
  if (inR(0.66, 0.64, 0.74, 0.69)) return hex('#ffffff');
  for (let k = 0; k < 4; k++) if (inR(0.16 + k * 0.175, 0.76, 0.16 + k * 0.175 + 0.14, 0.83)) return hex('#2b3a52');
  return hex('#0d1117');
}
function icon(size, maskable) {
  const S = 4, buf = Buffer.alloc(size * size * 4);
  for (let py = 0; py < size; py++) {
    for (let px = 0; px < size; px++) {
      const acc = [0, 0, 0, 0];
      for (let sy = 0; sy < S; sy++) for (let sx = 0; sx < S; sx++) {
        const c = iconColor((px + (sx + 0.5) / S) / size, (py + (sy + 0.5) / S) / size, maskable);
        if (c) { acc[0] += c[0]; acc[1] += c[1]; acc[2] += c[2]; acc[3] += 255; }
      }
      const n = S * S, a = acc[3] / n, o = (py * size + px) * 4;
      if (a) { buf[o] = Math.round(acc[0] / (acc[3] / 255)); buf[o + 1] = Math.round(acc[1] / (acc[3] / 255)); buf[o + 2] = Math.round(acc[2] / (acc[3] / 255)); }
      buf[o + 3] = Math.round(a);
    }
  }
  return png(size, size, buf);
}

// ---------------------------------------------------------------------------------------------------------------
// Output
// ---------------------------------------------------------------------------------------------------------------
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'icons'), { recursive: true });
for (const f of fs.readdirSync(path.join(HERE, 'public'))) fs.copyFileSync(path.join(HERE, 'public', f), path.join(OUT, f));
fs.writeFileSync(path.join(OUT, 'lspf-bundle.js'), bundle);
fs.writeFileSync(path.join(OUT, 'icons', 'icon-192.png'), icon(192, false));
fs.writeFileSync(path.join(OUT, 'icons', 'icon-512.png'), icon(512, false));
fs.writeFileSync(path.join(OUT, 'icons', 'icon-maskable-512.png'), icon(512, true));

const cached = ['./', 'index.html', 'app.css', 'lspf-bundle.js', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png'];
const hash = crypto.createHash('sha256');
for (const f of cached.slice(1)) hash.update(fs.readFileSync(path.join(OUT, f)));
const version = hash.digest('hex').slice(0, 12);
fs.writeFileSync(path.join(OUT, 'sw.js'), fs.readFileSync(path.join(HERE, 'src-sw', 'sw.js'), 'utf8')
  .replace(/__VERSION__/g, version).replace(/__FILES__/g, JSON.stringify(cached)));

const kb = (n) => (n / 1024).toFixed(0) + ' KB';
console.log(`lspf PWA ${BUILD.version} built in ${path.relative(process.cwd(), OUT) || OUT}`);
console.log(`  ${modules.length} modules, ${assets.length} library files (${kb(assetBytes)}), bundle ${kb(Buffer.byteLength(bundle))}, cache ${version}`);
